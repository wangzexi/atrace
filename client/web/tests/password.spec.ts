import { test, expect } from '@playwright/test'

test('设置菜单进入子页面，支持返回、刷新和清空未提交密码', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('密码', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.goto('/settings/')
  const menu = page.getByRole('navigation', { name: '设置分类' })
  await expect(menu.getByRole('link')).toHaveCount(4)
  await expect(page.getByLabel('当前密码', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('网站标题', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: '/tmp/atrace-settings-menu.png' })
  await menu.getByRole('link', { name: '网站 标题和页脚' }).click()
  await expect(page).toHaveURL('/settings/site/')
  await expect(page.getByRole('heading', { name: '网站', exact: true })).toBeVisible()
  await expect(page.getByLabel('网站标题', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(menu).toBeVisible()
  await menu.getByRole('link', { name: '修改密码 更新登录密码' }).click()
  const current = page.getByLabel('当前密码', { exact: true })
  const next = page.getByLabel('新密码（至少 8 个字符）', { exact: true })
  await expect(current).toBeVisible()
  const a = await current.boundingBox()
  const b = await next.boundingBox()
  expect(b!.y - a!.y - a!.height).toBeGreaterThanOrEqual(10)
  await current.fill('unsaved-password')
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(menu).toBeVisible()
  await menu.getByRole('link', { name: '修改密码 更新登录密码' }).click()
  await expect(current).toHaveValue('')
  await page.reload()
  await expect(page.getByRole('heading', { name: '修改密码', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page).toHaveURL('/settings/')
  await expect(menu).toBeVisible()
  await menu.getByRole('link', { name: '设备 在线设备与采集状态' }).click()
  await expect(page.getByRole('heading', { name: '设备', exact: true })).toBeVisible()
  await page.goBack()
  await expect(menu).toBeVisible()
})
